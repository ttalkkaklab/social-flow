#!/usr/bin/env python3
"""Build bundled font metadata with fontTools; never required on an installed plugin."""
from pathlib import Path
import hashlib
import json
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
REFS = ROOT / 'skills/storyboard/references'
FONT_ROOT = REFS / 'motion-fonts'
entries = {}
paths = [(p.stem, p) for p in sorted(FONT_ROOT.glob('*.ttf'))]
paths.append(('pretendard', ROOT / 'skills/channel/references/review-assets/fonts/PretendardVariable.woff2'))
for name, path in paths:
    font = TTFont(path)
    points = sorted(font.getBestCmap())
    ranges = []
    for point in points:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    axes = {axis.axisTag: [axis.minValue, axis.defaultValue, axis.maxValue]
            for axis in font['fvar'].axes} if 'fvar' in font else {}
    entries[name] = {'file': path.name, 'family': 'Motion_' + name,
                     'weight': font['OS/2'].usWeightClass, 'axes': axes,
                     'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                     'coverage': ranges}
(REFS / 'motion-font-data.js').write_text(
    '/* Generated by tools/build-motion-fonts.py from bundled cmap tables. */\n'
    '(function(root){const fonts=' + json.dumps(entries, separators=(',', ':')) + ';\n'
    "if(typeof module==='object'&&module.exports)module.exports=fonts;else root.MOTION_FONT_DATA=fonts;\n"
    "})(typeof window==='object'?window:globalThis);\n")
