#!/usr/bin/env python3
"""Build bundled font metadata with fontTools; never required on an installed plugin."""
from pathlib import Path
import hashlib
import json
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
REFS = ROOT / 'skills/storyboard/references'
FONT_ROOT = REFS / 'motion-fonts'
REVIEW_FONTS = ROOT / 'skills/channel/references/review-assets/fonts'


def describe(name, path):
    font = TTFont(path)
    points = sorted(font.getBestCmap())
    ranges = []
    for point in points:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    axes = {axis.axisTag: [axis.minValue, axis.defaultValue, axis.maxValue]
            for axis in font['fvar'].axes} if 'fvar' in font else {}
    return {'file': path.name, 'family': 'Motion_' + name,
            'weight': font['OS/2'].usWeightClass, 'axes': axes,
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'coverage': ranges}


def write(target, entries, global_name):
    target.write_text(
        '/* Generated by tools/build-motion-fonts.py from bundled cmap tables. */\n'
        '(function(root){const fonts=' + json.dumps(entries, separators=(',', ':')) + ';\n'
        f"if(typeof module==='object'&&module.exports)module.exports=fonts;else root.{global_name}=fonts;\n"
        "})(typeof window==='object'?window:globalThis);\n")


motion = {p.stem: describe(p.stem, p) for p in sorted(FONT_ROOT.glob('*.ttf'))}
motion['pretendard'] = describe('pretendard', REVIEW_FONTS / 'PretendardVariable.woff2')
write(REFS / 'motion-font-data.js', motion, 'MOTION_FONT_DATA')

# The cover's CJK faces live in their own file: motion slides emit an @font-face for every
# entry of motion-font-data.js, and these three files are megabytes each.
cover = {name: describe(name, REVIEW_FONTS / f'{stem}Variable.woff2')
         for name, stem in [('notosansjp', 'NotoSansJP'), ('notosanssc', 'NotoSansSC'), ('notosanstc', 'NotoSansTC')]}
write(ROOT / 'skills/generate-cover/references/cover-font-data.js', cover, 'COVER_FONT_DATA')
